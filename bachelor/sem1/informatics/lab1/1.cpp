#include <iostream> // Подключаем библиотеку ввода и вывода данных
using namespace std; // Используем стандартное пространство имен

// Задаём функцию ff (float)
float ff(float a, float b){
    cout << "start float ------------------------------------" << endl;

    float c = a + b; // Вычисляем сумму аргументов a и b и сохраняем в переменную c
    cout << "a + b = " << c << endl; // Выводим промежуточный результат сложения на экран
    
    float d = c * c * c; // Возводим полученную сумму c в куб (вычисляем c * c * c) и сохраняем в d
    cout << "(a + b) ^ 3 = " << d << endl; // Выводим куб суммы на экран

    float e = a * a * a; // Возводим первый аргумент a в куб и сохраняем в переменную e
    cout << "a ^ 3 = " << e << endl; // Выводим куб числа a на экран
    
    float f = 3 * a * a * b; // Вычисляем утроенное произведение квадрата a на b и сохраняем в f
    cout << "3 * a ^ 2 * b = " << f << endl; // Выводим результат на экран
    
    float g = e + f; // Находим сумму куба a и утроенного произведения, сохраняем в g
    cout << "a ^ 3 + 3 * a ^ 2 * b = " << g << endl; // Выводим полученную сумму на экран

    float h = d - g; // Вычисляем числитель формулы (разность d и g) и сохраняем в h
    cout << "(a + 3) ^ 3 - (a ^ 3 + 3 * a ^ 2 * b) = " << h << endl; // Выводим разность на экран
   
    float i = 3 * a * b * b; // Вычисляем утроенное произведение a на квадрат b, сохраняем в i
    cout << "3 * a * b * b = " << i << endl; // Выводим результат вычисления на экран
    
    float j = b * b * b; // Возводим второй аргумент b в куб и сохраняем в переменную j
    cout << "b ^ 3 = " << j << endl; // Выводим куб числа b на экран

    float k = i + j; // Находим знаменатель формулы (суммируем i и j) и сохраняем в k
    cout << "3 * a * b ^ 2 + b ^ 3 = " << k << endl; // Выводим полученный знаменатель на экран

    float answer = h / k; // Находим итоговый ответ делением числителя h на знаменатель k
    cout << "(a + 3) ^ 3 - (a ^ 3 + 3 * a ^ 2 * b) / (3 * a * b ^ 2 + b ^ 3) = " << answer << endl; // Выводим финальное выражение

    cout << "end float ------------------------------------" << endl;
    cout << "float result: " << endl;
    
    return answer; // Возвращаем полученный ответ типа float
}

// Задаём функцию dd (double)
double dd(double a, double b) {
    cout << "start double ------------------------------------" << endl;
    
    double c = a + b; // Находим сумму аргументов высокой точности и сохраняем в c
    cout << "a + b = " << c << endl; // Выводим промежуточную сумму на экран
    
    double d = c * c * c; // Возводим сумму c в куб и сохраняем в переменную d
    cout << "(a + b) ^ 3 = " << d << endl; // Выводим куб суммы на экран
    
    double e = a * a * a; // Возводим число a в куб и сохраняем в переменную e
    cout << "a ^ 3 = " << e << endl; // Выводим куб числа a на экран
    
    double f = 3 * a * a * b; // Вычисляем утроенное произведение квадрата a на b и сохраняем в f
    cout << "3 * a ^ 2 * b = " << f << endl; // Выводим результат вычисления на экран
    
    double g = e + f; // Находим частичную сумму куба a и утроенного произведения, сохраняем в g
    cout << "a ^ 3 + 3 * a ^ 2 * b = " << g << endl; // Выводим сумму на экран
    
    double h = d - g; // Вычисляем числитель (разность d и g) высокой точности и сохраняем в h
    cout << "(a + b) ^ 3 - (a ^ 3 + 3 * a ^ 2 * b) = " << h << endl; // Выводим числитель на экран
    
    double i = 3 * a * b * b; // Вычисляем утроенное произведение a на квадрат b, сохраняем в i
    cout << "3 * a * b * b = " << i << endl; // Выводим результат вычисления на экран
    
    double j = b * b * b; // Возводим число b в куб высокой точности и сохраняем в переменную j
    cout << "b ^ 3 = " << j << endl; // Выводим куб числа b на экран
    
    double k = i + j; // Вычисляем знаменатель формулы (суммируем i и j) высокой точности и сохраняем в k
    cout << "3 * a * b ^ 2 + b ^ 3 = " << k << endl; // Выводим знаменатель на экран
    
    double answer = h / k; // Находим итоговый точный ответ делением числителя h на знаменатель k
    cout << "((a + b) ^ 3 - (a ^ 3 + 3 * a ^ 2 * b)) / (3 * a * b ^ 2 + b ^ 3) = " << answer << endl; // Выводим точный ответ
    
    cout << "end double --------------------------------------" << endl;
    cout << "double result: " << endl;
    
    return answer; // Возвращаем полученный ответ типа double
}

int main() {
    
    cout << ff(1000, 0.0001) << endl;  // Вычисляем функцию ff от a = 1000, b = 0.0001
    cout << "\n"; // Печатаем в консоль пустую строку для визуального разделения блоков результатов
    cout << dd(1000, 0.0001) << endl; // Вычисляем функцию dd от a = 1000, b = 0.0001

    return 0; // Маркер успешного завершения программы
}
