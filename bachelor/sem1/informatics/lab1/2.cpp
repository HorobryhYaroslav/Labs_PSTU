#include <iostream>  // Подключаем библиотеку для ввода и вывода данных
#include <clocale>   // Подключаем библиотеку для корректной настройки отображения языков

using namespace std; // Используем стандартное пространство имён

int main() {
    // Включаем поддержку русского языка
    setlocale(LC_ALL, ".65001");

    int n; // Объявляем целочисленную переменную n для хранения первого числа
    int m; // Объявляем целочисленную переменную m для хранения второго числа

    // Ввод значения переменной n
    cout << "Введите n: ";
    cin >> n;

    // Ввод значения переменной m
    cout << "Введите m: ";
    cin >> m;

    // Шаг 1: Вычисляем выражение (n-- - m)
    // Так как декремент постфиксный (n--), сначала из текущего n вычитается m, результат выводится на экран,
    // После этого значение n уменьшается на 1.
    cout << "1. " << (n-- - m) << endl;

    // Шаг 2: Проверяем условие (m-- < n)
    // Так как декремент постфиксный (m--), сначала текущее значение m сравнивается с обновлённым значением n.
    // Выводится результат логического сравнения (1 - если истина, 0 - если ложь).
    // После этого значение m уменьшается на 1.
    cout << "2. " << (m-- < n) << endl;

    // Шаг 3: Проверяем условие (n++ > m)
    // Так как инкремент постфиксный (n++), сначала текущее значение n сравнивается с обновлённым значением m.
    // Выводится результат сравнения (1 или 0).
    // После этого значение n увеличивается на 1.
    cout << "3. " << (n++ > m) << endl;

    return 0; // Маркер успешного выполнения программы
}
